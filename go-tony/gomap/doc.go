// Package gomap converts between Go values and Tony IR nodes, and through the
// IR to and from encoded documents.
//
// # Usage
//
//	type User struct {
//	    Name  string `tony:"field=name"`
//	    Age   int    `tony:"field=age,omitzero"`
//	    Token string `tony:"omit"`
//	}
//	user := User{Name: "ada", Token: "secret"}
//
//	// Go value to IR, and IR to Go value
//	node, err := gomap.ToTonyIR(user)
//	var decoded User
//	err = gomap.FromTonyIR(node, &decoded)
//
//	// Go value to encoded bytes, and bytes to Go value
//	data, err := gomap.ToTony(user, gomap.EncodeWire(true))
//	err = gomap.FromTony(data, &decoded, gomap.Strict())
//
// The package handles conversion between Tony's IR representation and
// native Go types, including structs, maps, slices, and primitives.
//
// # Codecs
//
// [ToTonyIR] and [FromTonyIR] hand a value to its type's own codec when the
// type declares one:
//
//	ToTonyIR(opts ...gomap.MapOption) (*ir.Node, error)
//	FromTonyIR(node *ir.Node, opts ...gomap.UnmapOption) error
//
// with or without the options parameter. Code generated by
// [github.com/signadot/tony-format/go-tony/gomap/codegen] provides these
// methods, and hand-written ones are called the same way. A method a struct
// only inherits from an embedded field is not its codec. A type with no codec
// that implements [encoding.TextMarshaler] or [encoding.TextUnmarshaler] maps
// to and from a string, and any other value is mapped by reflection.
//
// Codecs are used for the values a value contains — fields, elements, map
// values — as well as for the value passed in. When encoding, a ToTonyIR
// declared on the pointer type, as generated ones are, is used for a contained
// value only when that value is addressable, as encoding/json does with
// MarshalJSON: a slice element, or a field of a struct reached through a
// pointer, but not a map value.
//
// # Struct fields
//
// Reflection maps a struct's exported fields, reading the tony struct tag:
//
//   - field=name sets the field's key; without it the key is the Go field name.
//   - omit, - and field=- exclude the field from encoding and decoding.
//   - omitzero drops the field when it holds its zero value: an empty slice,
//     map or array, a nil pointer or interface, or a zero scalar or struct.
//   - comment=F and lineComment=F name []string fields of the same struct
//     that carry the head and line comments of this field's value.
//
// Embedded structs are flattened into the parent's keys, and a field the
// parent declares itself shadows one it embeds; an embedded unexported struct
// type contributes its exported fields. Decoding matches keys case-sensitively,
// accepts a field under its field= name or its Go field name, and by default
// ignores a key the type does not declare (see [Strict]).
//
// A map with string keys maps to an object and one with uint32 keys to a
// !sparsearray object; a nil map maps to null and an empty one to {}.
//
// # Schema-aware mapping
//
// A struct names its schema with an anonymous marker field tagged
// tony:"schemagen=name" or tony:"schema=name", whose type may be unexported
// (see [GetStructSchema]). The marker's comment=F and lineComment=F name the
// fields that carry the struct's own head and line comments. A [Mapper]
// resolves the schema name in its schema registry and, when it finds the
// schema, maps the struct's fields by [GetStructFields].
//
// # Related Packages
//
//   - github.com/signadot/tony-format/go-tony/ir - IR representation
//   - github.com/signadot/tony-format/go-tony/gomap/codegen - Code generation
